//! Reed FM-1 table generator.
//!
//! Reads the physics/calibration of OpenWurli (GPL-3.0-or-later) and writes the
//! fixed-point tables the FM-1 engine uses. The generated C is committed, so a
//! normal build needs neither Rust nor network access; this tool exists so the
//! tables can be regenerated when OpenWurli's calibration changes.
//!
//!     cargo run --release > ../../engine/src/wurli_tables.c
//!
//! Everything printed here is derived data from OpenWurli and inherits its
//! GPL-3.0-or-later licence.

use std::f64::consts::{PI, TAU};
use std::fmt::Write as _;

use openwurli_dsp::pickup::{
    pickup_band_sign, pickup_law_for, PickupLawTable, PICKUP_REST_OFFSET_MM,
};
use openwurli_dsp::tables::{self, CalibrationConfig};
use openwurli_dsp::variation;

const FS: f64 = 44100.0;
const NNOTE: usize = 64; // MIDI 33..=96
const MIDI_LO: u8 = 33;
const NVEL: usize = 64; // velocity layers (MIDI velocity 0..127, 64 layers)
const NLAW: usize = 4;
const WR_TANH_N: usize = 512;
const WR_EXP_N: usize = 256;
const WR_ONSET_N: usize = 256;
const WR_TUNE_N: usize = 101;
const WR_VOL_N: usize = 128;
const WR_SIN_N: usize = 1024;
const WR_SPK_N: usize = 33;

fn q30(x: f64) -> i32 {
    (x * (1i64 << 30) as f64).round() as i64 as i32
}
fn q28(x: f64) -> i32 {
    (x * (1i64 << 28) as f64).round() as i64 as i32
}
fn q24(x: f64) -> i32 {
    (x * (1i64 << 24) as f64).round() as i64 as i32
}
fn q16(x: f64) -> i32 {
    (x * (1i64 << 16) as f64).round() as i64 as i32
}

fn law_index(midi: u8) -> usize {
    match midi.saturating_sub(32) {
        0..=14 => 0,
        15..=20 => 1,
        21..=42 => 2,
        _ => 3,
    }
}

fn laws() -> [&'static PickupLawTable; NLAW] {
    // The four sections are selected through the public per-note function; ask
    // it for one representative note per section.
    [
        pickup_law_for(33),
        pickup_law_for(47),
        pickup_law_for(64),
        pickup_law_for(90),
    ]
}

fn main() {
    let cfg = CalibrationConfig::default();
    let mut out = String::with_capacity(1 << 20);

    out.push_str(
        "/* SPDX-License-Identifier: GPL-3.0-only\n\
         * GENERATED by tools/tablegen — do not edit.\n\
         * Derived from OpenWurli (GPL-3.0-or-later) physics and calibration:\n\
         *   https://github.com/hal0zer0/openwurli @ 531680b5b49eb4a734a8d8ef7a9c13cb83cf79f9\n\
         * Regenerate: cd tools/tablegen && cargo run --release > ../../engine/src/wurli_tables.c\n\
         */\n\
         #include \"wurli_tables.h\"\n\n",
    );

    // ── Pickup laws ─────────────────────────────────────────────────────────
    for (k, law) in laws().iter().enumerate() {
        writeln!(out, "static const int32_t wr_law{}_y[{}] = {{", k, law.y.len()).unwrap();
        for chunk in law.y.chunks(6) {
            out.push_str("    ");
            for v in chunk {
                write!(out, "{},", q30(*v)).unwrap();
            }
            out.push('\n');
        }
        out.push_str("};\n");

        let h2 = law.du * law.du / 6.0;
        writeln!(
            out,
            "static const int32_t wr_law{}_mh[{}] = {{",
            k,
            law.m.len()
        )
        .unwrap();
        for chunk in law.m.chunks(6) {
            out.push_str("    ");
            for v in chunk {
                write!(out, "{},", q30(*v * h2)).unwrap();
            }
            out.push('\n');
        }
        out.push_str("};\n");
    }

    out.push_str("const wr_pickup_law_t wr_laws[WR_NLAW] = {\n");
    for (k, law) in laws().iter().enumerate() {
        writeln!(
            out,
            "    {{ {}, {}, {}, {}, wr_law{}_y, wr_law{}_mh }},",
            q16(law.u0),
            q16(law.du),
            (65536.0 * 65536.0 / q16(law.du) as f64).round() as i64,
            law.y.len(),
            k,
            k
        )
        .unwrap();
    }
    out.push_str("};\n\n");

    // ── Per-note constants ──────────────────────────────────────────────────
    out.push_str("const wr_note_t wr_notes[WR_NNOTE] = {\n");
    for midi in MIDI_LO..MIDI_LO + NNOTE as u8 {
        let p = tables::note_params(midi);
        let detune = variation::freq_detune(midi);
        let f0 = p.fundamental_hz * detune;
        let offsets = variation::mode_amplitude_offsets(midi);
        let swing = tables::pickup_swing_mm_with_config(midi, &cfg);
        let drag = tables::air_drag_db_per_mm_with_config(midi, &cfg);
        let law = pickup_law_for(midi);
        let c_rest = law.eval(-PICKUP_REST_OFFSET_MM);

        // Damper: OpenWurli's start_damper(), per 32-sample control block.
        let damper_rate = |m: usize| -> f64 {
            if midi >= 92 {
                return 0.0;
            }
            let base = (55.0 * 2f64.powf((midi as f64 - 60.0) / 24.0)).max(0.5);
            (base * 3f64.powi(m as i32)).min(2000.0)
        };
        let ramp_s = if midi < 48 {
            0.050
        } else if midi < 72 {
            0.025
        } else {
            0.008
        };

        // Attack-noise band-pass: RBJ, constant 0 dB peak (as OpenWurli's Biquad).
        let noise_fc = (f0 * 5.0).clamp(200.0, 2000.0);
        let w0 = TAU * noise_fc / FS;
        let alpha = w0.sin() / (2.0 * 0.7);
        let a0 = 1.0 + alpha;

        out.push_str("    {\n        .inc = {");
        for i in 0..7 {
            let inc = (f0 * p.mode_ratios[i] / FS * (1u64 << 32) as f64).round() as u64;
            write!(out, "{},", inc as u32).unwrap();
        }
        out.push_str("},\n        .cos = {");
        for i in 0..7 {
            let w = TAU * f0 * p.mode_ratios[i] / FS;
            write!(out, "{},", q30(w.cos())).unwrap();
        }
        out.push_str("},\n        .sin = {");
        for i in 0..7 {
            let w = TAU * f0 * p.mode_ratios[i] / FS;
            write!(out, "{},", q30(w.sin())).unwrap();
        }
        out.push_str("},\n        .amp = {");
        for i in 0..7 {
            write!(out, "{},", q30(p.mode_amplitudes[i] * offsets[i])).unwrap();
        }
        out.push_str("},\n        .decay = {");
        for i in 0..7 {
            let a = p.mode_decay_rates[i] / 8.686 / FS;
            write!(out, "{},", q30((-a * 32.0).exp())).unwrap();
        }
        out.push_str("},\n        .damper = {");
        for m in 0..7 {
            let a = damper_rate(m) / FS;
            write!(out, "{},", q30((-a * 32.0).exp())).unwrap();
        }
        out.push_str("},\n        .ratio = {");
        for i in 0..7 {
            write!(out, "{},", q16(p.mode_ratios[i])).unwrap();
        }
        write!(
            out,
            "}},\n        .f0_q16 = {}, .swing_q16 = {}, .drag_q30 = {},\n",
            q16(f0),
            q16(swing),
            q30(drag / 8.686 * swing / FS * 32.0)
        )
        .unwrap();
        writeln!(
            out,
            "        .c_rest = {}, .damper_ramp = {},\n        .law = {}, .band = {},\n        .noise_b0 = {}, .noise_b2 = {}, .noise_a1 = {}, .noise_a2 = {},",
            q30(c_rest),
            (ramp_s * FS) as u32,
            law_index(midi),
            if pickup_band_sign(midi) > 0.0 { 1 } else { -1 },
            q28(alpha / a0),
            q28(-alpha / a0),
            q28(-2.0 * w0.cos() / a0),
            q28((1.0 - alpha) / a0)
        )
        .unwrap();
        out.push_str("    },\n");
    }
    out.push_str("};\n\n");

    // ── Velocity: drive into the pickup and post-pickup output gain ─────────
    // 64 layers, linearly interpolated at note-on.
    out.push_str("const int32_t wr_vel_drive[WR_NNOTE][WR_NVEL] = {\n");
    for midi in MIDI_LO..MIDI_LO + NNOTE as u8 {
        out.push_str("    {");
        let exp = tables::velocity_exponent(midi);
        for k in 0..NVEL {
            let v = k as f64 / (NVEL - 1) as f64;
            let x = tables::velocity_scurve(v).powf(exp);
            write!(out, "{},", q30(x)).unwrap();
        }
        out.push_str("},\n");
    }
    out.push_str("};\n\n");

    out.push_str("const int32_t wr_out_gain[WR_NNOTE][WR_NVEL] = {\n");
    for midi in MIDI_LO..MIDI_LO + NNOTE as u8 {
        out.push_str("    {");
        for k in 0..NVEL {
            let v = k as f64 / (NVEL - 1) as f64;
            let g = tables::output_scale_with_config(midi, v, &cfg);
            write!(out, "{},", q24(g)).unwrap();
        }
        out.push_str("},\n");
    }
    out.push_str("};\n\n");

    // ── Shared curves ───────────────────────────────────────────────────────
    out.push_str("const int32_t wr_tanh_tab[WR_TANH_N + 1] = {\n");
    for i in 0..=WR_TANH_N {
        let x = -4.0 + 8.0 * i as f64 / WR_TANH_N as f64;
        write!(out, "{},", q24(x.tanh())).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    out.push_str("const int32_t wr_expneg_tab[WR_EXP_N + 1] = {\n");
    for i in 0..=WR_EXP_N {
        let z = i as f64 / 16.0;
        write!(out, "{},", q30((-z).exp())).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    out.push_str("const int32_t wr_onset_tab[WR_ONSET_N + 1] = {\n");
    for i in 0..=WR_ONSET_N {
        let t = i as f64 / WR_ONSET_N as f64;
        write!(out, "{},", q30(0.5 - 0.5 * (PI * t).cos())).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    // Global tuning: -50..+50 cents.
    out.push_str("const int32_t wr_sin_tab[WR_SIN_N + 1] = {\n");
    for i in 0..=WR_SIN_N {
        let ph = TAU * i as f64 / WR_SIN_N as f64;
        write!(out, "{},", q30(ph.sin())).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    out.push_str("const int32_t wr_tune_tab[WR_TUNE_N] = {\n");
    for i in 0..WR_TUNE_N {
        let cents = i as f64 - 50.0;
        write!(out, "{},", q30(2f64.powf(cents / 1200.0))).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    // Volume-pot network at OpenWurli's R-11 factory trim (17.2k).
    out.push_str("const int32_t wr_vol_gain_tab[WR_VOL_N] = {\n");
    for i in 0..WR_VOL_N {
        let vol = i as f64 / (WR_VOL_N - 1) as f64;
        let g = tables::volume_pot_gain(vol, tables::R11_REED_BAR_VOLUME_DEFAULT);
        write!(out, "{},", q24(g)).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    // Speaker polynomial normalisation: 1 / (1 + 0.8 c), 33 steps.
    out.push_str("const int32_t wr_spk_inv_tab[WR_SPK_N] = {\n");
    for i in 0..WR_SPK_N {
        let c = i as f64 / (WR_SPK_N - 1) as f64;
        write!(out, "{},", q30(1.0 / (1.0 + 0.8 * c))).unwrap();
        if i % 8 == 7 {
            out.push('\n');
        }
    }
    out.push_str("};\n\n");

    // ── Global constants ────────────────────────────────────────────────────
    let beta = PI * openwurli_dsp::pickup::PICKUP_FC / FS;
    let sens = openwurli_dsp::pickup::PICKUP_SENSITIVITY;
    let reed_ratio = 3.0e-12 / 240.0e-12;
    writeln!(
        out,
        "const wr_consts_t wr_consts = {{\n\
         \x20   .beta = {}, .inv_den = {}, .sens = {}, .reed_ratio = {},\n\
         \x20   .rest_q16 = {}, .fs = {},\n\
         \x20   .preamp_hpf = {}, .amp_shelf = {},\n\
         \x20   .spk_hp_b0 = {}, .spk_hp_b1 = {}, .spk_hp_b2 = {}, .spk_hp_a1 = {}, .spk_hp_a2 = {},\n\
         \x20   .spk_lp_b0 = {}, .spk_lp_b1 = {}, .spk_lp_b2 = {}, .spk_lp_a1 = {}, .spk_lp_a2 = {},\n\
         \x20   .trem_attack = {}, .trem_release = {},\n\
         \x20   .trem_phase_inc = {},\n\
         }};",
        q30(beta),
        q30(1.0 / (1.0 + beta)),
        q30(sens),
        q30(reed_ratio),
        q16(PICKUP_REST_OFFSET_MM),
        FS,
        q30(1.0 - (-TAU * 150.0 / FS).exp()), // one-pole HPF coefficient
        q30(1.0 - (-TAU * 33.0 / FS).exp()),  // power-amp feedback shelf (one-pole HPF)
        // Speaker HPF 30 Hz, Q 0.75
        q28(biquad(0, 30.0, 0.75)[0]),
        q28(biquad(0, 30.0, 0.75)[1]),
        q28(biquad(0, 30.0, 0.75)[2]),
        q28(biquad(0, 30.0, 0.75)[3]),
        q28(biquad(0, 30.0, 0.75)[4]),
        // Speaker LPF 6500 Hz, Q 0.707
        q28(biquad(1, 6500.0, 0.707)[0]),
        q28(biquad(1, 6500.0, 0.707)[1]),
        q28(biquad(1, 6500.0, 0.707)[2]),
        q28(biquad(1, 6500.0, 0.707)[3]),
        q28(biquad(1, 6500.0, 0.707)[4]),
        // Control rate is 32 samples.
        q30(1.0 - (-32.0 / (0.0025 * FS)).exp()),
        q30(1.0 - (-32.0 / (0.035 * FS)).exp()),
        (5.63 / FS * 32.0 * (1u64 << 32) as f64).round() as u64 as u32,
    )
    .unwrap();

    // ── Sanity values for the docs/tests ────────────────────────────────────
    writeln!(out, "\n/* calibration reference (not used by the engine):").unwrap();
    for midi in [33u8, 48, 60, 72, 84, 96] {
        let p = tables::note_params(midi);
        writeln!(
            out,
            " * MIDI {} f0 {:.2} Hz amp1 {:.5} decay1 {:.2} dB/s",
            midi,
            p.fundamental_hz,
            p.mode_amplitudes[0],
            p.mode_decay_rates[0]
        )
        .unwrap();
    }
    out.push_str(" */\n");

    print!("{out}");
}

/// RBJ biquad: 0 = high-pass, 1 = low-pass. Returns b0,b1,b2,a1,a2 normalized.
fn biquad(kind: u8, fc: f64, q: f64) -> [f64; 5] {
    let w0 = TAU * fc.min(FS * 0.499) / FS;
    let c = w0.cos();
    let s = w0.sin();
    let alpha = s / (2.0 * q);
    let a0 = 1.0 + alpha;
    if kind == 0 {
        [
            ((1.0 + c) / 2.0) / a0,
            -(1.0 + c) / a0,
            ((1.0 + c) / 2.0) / a0,
            (-2.0 * c) / a0,
            (1.0 - alpha) / a0,
        ]
    } else {
        [
            ((1.0 - c) / 2.0) / a0,
            (1.0 - c) / a0,
            ((1.0 - c) / 2.0) / a0,
            (-2.0 * c) / a0,
            (1.0 - alpha) / a0,
        ]
    }
}
